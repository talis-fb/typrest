import type { JsonValue, SchemaField } from "./api";

export interface CustomField {
  id: number;
  key: string;
  valueText: string;
}

export interface CustomFieldIssue {
  id: number;
  issue: string;
}

export function isJsonObject(value: JsonValue): value is Record<string, JsonValue> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function cloneJson<T extends JsonValue>(value: T): T {
  return JSON.parse(JSON.stringify(value)) as T;
}

export function seedField(field: SchemaField): JsonValue {
  if (Object.prototype.hasOwnProperty.call(field, "default")) {
    return cloneJson(field.default ?? null);
  }
  if (field.enum && field.enum.length > 0) {
    return cloneJson(field.enum[0]);
  }

  switch (field.type) {
    case "string":
      return "";
    case "number":
      return 0;
    case "boolean":
      return false;
    case "object":
      return seedObject(field);
    case "array":
      return [];
    case "null":
    default:
      return null;
  }
}

export function shouldSeedField(field: SchemaField): boolean {
  return Boolean(
    field.required ||
      Object.prototype.hasOwnProperty.call(field, "default") ||
      (field.enum && field.enum.length > 0),
  );
}

export function seedObject(field: SchemaField): Record<string, JsonValue> {
  const payload: Record<string, JsonValue> = {};
  for (const [name, property] of Object.entries(field.properties ?? {})) {
    if (shouldSeedField(property)) {
      payload[name] = seedField(property);
    }
  }
  return payload;
}

export function hydrateObjectForForm(
  payload: Record<string, JsonValue>,
  field: SchemaField,
): Record<string, JsonValue> {
  const hydrated = cloneJson(payload);

  for (const [name, property] of Object.entries(field.properties ?? {})) {
    if (!Object.prototype.hasOwnProperty.call(hydrated, name)) {
      if (shouldSeedField(property)) {
        hydrated[name] = seedField(property);
      }
      continue;
    }

    if (property.type === "object" && isJsonObject(hydrated[name])) {
      hydrated[name] = hydrateObjectForForm(
        hydrated[name] as Record<string, JsonValue>,
        property,
      );
    }
  }

  return hydrated;
}

export function splitRawObject(
  payload: Record<string, JsonValue>,
  schemaFields: Record<string, SchemaField>,
): { known: Record<string, JsonValue>; custom: CustomField[] } {
  const known: Record<string, JsonValue> = {};
  const custom: CustomField[] = [];
  let id = 1;

  for (const [key, value] of Object.entries(payload)) {
    if (Object.prototype.hasOwnProperty.call(schemaFields, key)) {
      known[key] = cloneJson(value);
    } else {
      custom.push({ id: id++, key, valueText: JSON.stringify(value, null, 2) });
    }
  }

  return { known, custom };
}

export function composeFormPayload(
  known: Record<string, JsonValue>,
  custom: CustomField[],
  schemaFields: Record<string, SchemaField>,
): { payload: Record<string, JsonValue> | null; issues: CustomFieldIssue[] } {
  const payload = cloneJson(known);
  const issues: CustomFieldIssue[] = [];
  const seen = new Set<string>();

  for (const field of custom) {
    const key = field.key.trim();
    if (!key) {
      issues.push({ id: field.id, issue: "Custom field key is required" });
      continue;
    }
    if (Object.prototype.hasOwnProperty.call(schemaFields, key)) {
      issues.push({ id: field.id, issue: `"${key}" is generated by the schema` });
      continue;
    }
    if (seen.has(key)) {
      issues.push({ id: field.id, issue: `Duplicate custom field "${key}"` });
      continue;
    }
    seen.add(key);

    try {
      payload[key] = JSON.parse(field.valueText) as JsonValue;
    } catch {
      issues.push({ id: field.id, issue: `Value for "${key}" is not valid JSON` });
    }
  }

  return { payload: issues.length === 0 ? payload : null, issues };
}
