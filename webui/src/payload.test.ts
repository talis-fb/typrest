import { describe, expect, it } from "vitest";
import {
  composeFormPayload,
  hydrateObjectForForm,
  seedObject,
  splitRawObject,
  type CustomField,
} from "./payload";
import type { SchemaField } from "./api";

const root: SchemaField = {
  type: "object",
  properties: {
    name: { type: "string", required: true },
    currency: { type: "string", enum: ["BRL", "USD"] },
    note: { type: "string" },
    nested: {
      type: "object",
      required: true,
      properties: {
        enabled: { type: "boolean", default: true },
      },
    },
  },
};

describe("payload form utilities", () => {
  it("seeds required, defaulted, enum, and recursive fields", () => {
    expect(seedObject(root)).toEqual({
      name: "",
      currency: "BRL",
      nested: { enabled: true },
    });
  });

  it("splits schema fields from custom raw fields", () => {
    const split = splitRawObject(
      { name: "Ada", debug: { trace: true } },
      root.properties ?? {},
    );

    expect(split.known).toEqual({ name: "Ada" });
    expect(split.custom[0]).toMatchObject({ key: "debug" });
    expect(JSON.parse(split.custom[0].valueText)).toEqual({ trace: true });
  });

  it("restores required and defaulted nested values when entering form mode", () => {
    expect(
      hydrateObjectForForm(
        {
          nested: {},
        },
        root,
      ),
    ).toEqual({
      name: "",
      currency: "BRL",
      nested: { enabled: true },
    });
  });

  it("rejects schema collisions and duplicate custom keys", () => {
    const custom: CustomField[] = [
      { id: 1, key: "name", valueText: '"override"' },
      { id: 2, key: "debug", valueText: "true" },
      { id: 3, key: "debug", valueText: "false" },
    ];

    const result = composeFormPayload({}, custom, root.properties ?? {});

    expect(result.payload).toBeNull();
    expect(result.issues.map((issue) => issue.issue)).toEqual([
      '"name" is generated by the schema',
      'Duplicate custom field "debug"',
    ]);
  });

  it("rejects invalid custom JSON and preserves JSON value types", () => {
    const invalid = composeFormPayload(
      {},
      [{ id: 1, key: "debug", valueText: "{" }],
      root.properties ?? {},
    );
    expect(invalid.payload).toBeNull();

    const valid = composeFormPayload(
      { name: "Ada" },
      [{ id: 2, key: "attempts", valueText: "3" }],
      root.properties ?? {},
    );
    expect(valid.payload).toEqual({ name: "Ada", attempts: 3 });
  });
});
